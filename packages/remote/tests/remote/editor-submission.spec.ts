/** Submission admission, draft recovery, and exact-selection cancellation decisions. @module mayfly-remote/tests/editor-submission */
import { describe, expect, it, vi } from 'vitest'
import type { MessageId } from '@deepseek-ai/dsh-llm/brand'
import { accepted, denied, deferred, flush, submissionFixture, wire } from './editor-feature-fixture.ts'

describe('editor submission through the real core editor', () => {
  it('uses one request identity for the selected Host prompt and preserves native history', async () => {
    const host = wire()
    const f = submissionFixture(host.selected)
    f.enter('  explain this change  ')
    await flush()
    expect(host.prompt).toHaveBeenCalledOnce()
    expect(host.prompt).toHaveBeenCalledWith([{ type: 'text', text: 'explain this change' }], 'queue', expect.any(AbortSignal), host.handles[0]!.requestId)
    expect(f.editor.getText()).toBe('')
    expect(f.editor.getHistory()).toContain('explain this change')
    expect(host.handles[0]!.abandon).not.toHaveBeenCalled()
  })
  it('rewrites settled skill tokens and uses steer without replaying the normal Enter lane', async () => {
    const host = wire()
    const f = submissionFixture(host.selected)
    await f.skills.refresh()
    f.editor.setText('  use #review now  ')
    expect(f.submit.steer()).toBe(true)
    await flush()
    expect(host.prompt).toHaveBeenCalledWith([{ type: 'text', text: 'use /review now' }], 'steer', expect.any(AbortSignal), host.handles[0]!.requestId)
    expect(f.editor.getText()).toBe('')
    expect(f.submit.steer()).toBe(false)
    f.enter('   ')
    expect(host.prompt).toHaveBeenCalledOnce()
  })

  it('creates the initial Session only when a prompt is submitted and routes the same draft once', async () => {
    const host = wire()
    const ensure = deferred<typeof host.selected>()
    const create = vi.fn(() => ensure.promise)
    const f = submissionFixture(undefined, create)
    f.select(undefined)
    expect(create).not.toHaveBeenCalled()
    f.enter('first prompt')
    expect(create).toHaveBeenCalledOnce()
    expect(host.prompt).not.toHaveBeenCalled()
    f.select(host.selected)
    ensure.resolve(host.selected)
    await flush()
    expect(host.prompt).toHaveBeenCalledOnce()
    expect(host.begin[0]!.text).toBe('first prompt')
  })

  it('preserves the original native draft and removes failed history when no Session can be obtained', async () => {
    const f = submissionFixture()
    f.select(undefined)
    f.enter('  unsent draft  ')
    await flush()
    expect(f.editor.getText()).toBe('  unsent draft  ')
    expect(f.editor.getHistory()).not.toContain('unsent draft')
    expect(f.notices).toContain('Select or create a Session before prompting')
  })

  it('restores unconfirmed text and attachment receipts after a refusal without retrying', async () => {
    const host = wire()
    host.prompt.mockResolvedValueOnce(denied('Host declined the prompt'))
    const f = submissionFixture(host.selected)
    const marker = f.file()
    f.enter(`explain ${marker}`)
    await flush()
    expect(host.prompt).toHaveBeenCalledOnce()
    expect(host.prompt.mock.calls[0]![0]).toEqual([{ type: 'text', text: 'explain ' }, { type: 'file', receiptId: 'receipt-1' }])
    expect(f.editor.getText()).toBe(`explain ${marker}`)
    expect(f.attachments.capture(marker).content).toEqual([{ type: 'file', receiptId: 'receipt-1' }])
    expect(f.notices).toContain('Host declined the prompt')
  })

  it('keeps admitted drafts consumed after an ambiguous receipt failure', async () => {
    const host = wire()
    host.prompt.mockImplementation(async () => { host.begin[0]!.onAccept?.(); throw new Error('socket lost after admission') })
    const f = submissionFixture(host.selected)
    const marker = f.file()
    f.enter(`explain ${marker}`)
    await flush()
    expect(host.prompt).toHaveBeenCalledOnce()
    expect(host.handles[0]!.abandon).toHaveBeenCalledOnce()
    expect(f.editor.getText()).toBe('')
    expect(f.attachments.capture(marker).content).toEqual([{ type: 'text', text: marker }])
    expect(f.notices.at(-1)).toBe('Prompt accepted; confirmation ended early: socket lost after admission')
  })

  it('abandons an unaccepted echo and restores the original draft on transport exceptions', async () => {
    const host = wire()
    host.prompt.mockRejectedValueOnce(new Error('network failed'))
    const f = submissionFixture(host.selected)
    f.enter('keep this draft')
    await flush()
    expect(host.handles[0]!.abandon).toHaveBeenCalledOnce()
    expect(f.editor.getText()).toBe('keep this draft')
    expect(f.notices.at(-1)).toContain('no retry was sent: network failed')
    expect(host.prompt).toHaveBeenCalledOnce()
  })

  it('does not restore a refused echo that was independently accepted before its response arrived', async () => {
    const host = wire()
    host.prompt.mockImplementation(async () => { host.begin[0]!.onAccept?.(); return denied('late rejection') })
    const f = submissionFixture(host.selected)
    f.enter('already admitted')
    await flush()
    expect(f.editor.getText()).toBe('')
    expect(f.editor.getHistory()).toContain('already admitted')
  })

  it('never overwrites a newly typed draft with a late failure from the same Session', async () => {
    const host = wire()
    const response = deferred<Awaited<ReturnType<typeof host.prompt>>>()
    host.prompt.mockImplementationOnce(() => response.promise)
    const f = submissionFixture(host.selected)
    f.enter('old pending text')
    f.editor.setText('new draft still being edited')
    response.resolve(denied('offline'))
    await flush()
    expect(f.editor.getText()).toBe('new draft still being edited')
    expect(host.prompt).toHaveBeenCalledOnce()
  })

  it.each(['other Host', 'new connection generation', 'new client', 'detached'] as const)('ignores late prompt failures after switching to %s', async transition => {
    const host = wire()
    const response = deferred<Awaited<ReturnType<typeof host.prompt>>>()
    host.prompt.mockImplementationOnce(() => response.promise)
    const f = submissionFixture(host.selected)
    f.enter('pending on the first selection')
    f.select(transition === 'detached' ? undefined : transition === 'other Host' ? wire('two').selected : transition === 'new client' ? wire('one').selected : { ...host.selected, generation: 2 })
    response.reject(new Error('retired request failed'))
    await flush()
    expect(f.editor.getText()).toBe('')
    expect(f.notices).toEqual([])
    expect(host.prompt).toHaveBeenCalledOnce()
  })

  it('restores only the latest unaccepted submission when multiple requests finish out of order', async () => {
    const host = wire()
    const older = deferred<Awaited<ReturnType<typeof host.prompt>>>()
    const newer = deferred<Awaited<ReturnType<typeof host.prompt>>>()
    host.prompt.mockImplementationOnce(() => older.promise).mockImplementationOnce(() => newer.promise)
    const f = submissionFixture(host.selected)
    f.enter('older')
    f.enter('newer')
    older.resolve(denied('older refused'))
    await flush()
    expect(f.editor.getText()).toBe('')
    newer.resolve(denied('newer refused'))
    await flush()
    expect(f.editor.getText()).toBe('newer')
    expect(new Set(host.handles.map(handle => handle.requestId)).size).toBe(2)
  })

  it('disposes a pending write by aborting the carrier and returning attachment ownership once', async () => {
    const host = wire()
    const response = deferred<Awaited<ReturnType<typeof host.prompt>>>()
    host.prompt.mockImplementationOnce(() => response.promise)
    const f = submissionFixture(host.selected)
    const marker = f.file()
    f.enter(`pending ${marker}`)
    const signal = host.prompt.mock.calls[0]![2]!
    f.submit.dispose()
    expect(signal.aborted).toBe(true)
    response.reject(new Error('aborted'))
    await flush()
    expect(f.editor.getText()).toBe('')
    expect(f.notices).toEqual([])
    expect(f.attachments.capture(marker).content).toEqual([{ type: 'file', receiptId: 'receipt-1' }])
  })

  it('does not submit to a Session created after the editor was disposed', async () => {
    const host = wire()
    const ensure = deferred<typeof host.selected>()
    const f = submissionFixture(undefined, () => ensure.promise)
    f.select(undefined)
    f.enter('late create')
    f.submit.dispose()
    ensure.resolve(host.selected)
    await flush()
    expect(host.prompt).not.toHaveBeenCalled()
    expect(f.notices).toEqual([])
  })

  it('restores a draft after initial Session creation fails without creating it again', async () => {
    const create = vi.fn(async () => { throw new Error('create refused') })
    const f = submissionFixture(undefined, create)
    f.select(undefined)
    f.enter('first prompt')
    await flush()
    expect(create).toHaveBeenCalledOnce()
    expect(f.editor.getText()).toBe('first prompt')
    expect(f.notices.at(-1)).toContain('create refused')
  })

  it('routes canonical local commands before any Session creation and exits only after success', async () => {
    const create = vi.fn(async () => wire().selected)
    const f = submissionFixture(undefined, create)
    f.select(undefined)
    f.local.list = () => [{ name: 'quit', description: 'Exit', aliases: ['q'] }]
    f.local.execute = vi.fn<typeof f.local.execute>(async invocation => {
      expect(invocation.line).toBe('/quit  now')
      return { kind: 'success', exit: true }
    })
    f.enter('/q  now')
    await flush()
    expect(f.exit).toHaveBeenCalledOnce()
    expect(create).not.toHaveBeenCalled()
  })

  it('refuses command file receipts explicitly and preserves both command text and receipt', async () => {
    const host = wire()
    const f = submissionFixture(host.selected)
    const marker = f.file()
    f.enter(`/host-only ${marker}`)
    await flush()
    expect(host.executeCommand).not.toHaveBeenCalled()
    expect(host.prompt).not.toHaveBeenCalled()
    expect(f.editor.getText()).toBe(`/host-only ${marker}`)
    expect(f.notices.at(-1)).toContain('Command file attachments require the focused Host command DTO')
    expect(f.attachments.capture(marker).content[0]!.type).toBe('file')
  })

  it('preserves failed command drafts and never prompts them as model text', async () => {
    const host = wire()
    const f = submissionFixture(host.selected)
    f.local.list = () => [{ name: 'fail', description: 'Refuse' }]
    f.local.execute = () => ({ kind: 'error', text: 'local refusal' })
    f.enter('/fail argument')
    await flush()
    expect(f.editor.getText()).toBe('/fail argument')
    expect(f.notices).toContain('local refusal')
    expect(host.prompt).not.toHaveBeenCalled()
  })

  it('clears to native history, restores removed queue text without sending, then requeues with fresh identities', async () => {
    const host = wire()
    const f = submissionFixture(host.selected)
    expect(f.submit.clearDraft()).toBe(false)
    f.editor.setText('recover with Up')
    expect(f.submit.clearDraft()).toBe(true)
    expect(f.editor.getText()).toBe('')
    expect(f.draft.currentHistory()).toContain('recover with Up')
    f.submit.restoreQueued('')
    f.submit.restoreQueued('removed queue draft')
    expect(f.editor.getText()).toBe('removed queue draft')
    expect(f.screen.setFocus).toHaveBeenCalledWith(f.editor)
    expect(host.prompt).not.toHaveBeenCalled()
    f.submit.requeue('  ', 'turn')
    f.submit.requeue('first queue', 'turn')
    f.submit.requeue('second queue', 'step')
    await flush()
    expect(host.prompt.mock.calls.map(call => call[1])).toEqual(['queue', 'steer'])
    expect(host.handles[0]!.requestId).not.toBe(host.handles[1]!.requestId)
  })

  it('restores a stashed multiline draft and history into another real editor without replaying submissions', () => {
    const host = wire()
    const f = submissionFixture(host.selected)
    f.draft.stashDraft({ raw: 'line one\nline two', pastes: new Map() })
    f.draft.stashHistory(['newest', 'oldest'], [undefined, undefined])
    f.submit.restoreEditor()
    expect(f.editor.getText()).toBe('line one\nline two')
    expect(f.editor.getHistory()).toEqual(['newest', 'oldest'])
    expect(host.prompt).not.toHaveBeenCalled()
  })

  it('forwards pending-queue mutations and cancellation exactly once and presents explicit failures', async () => {
    const host = wire()
    const f = submissionFixture(host.selected)
    const item = 'message-1' as MessageId
    expect(await f.submit.updateQueue(item, { kind: 'remove' })).toBe(true)
    expect(host.updateQueue).toHaveBeenCalledWith(item, { kind: 'remove' })
    host.updateQueue.mockResolvedValueOnce(denied('queue item already claimed'))
    expect(await f.submit.updateQueue(item, { kind: 'steer' })).toBe(false)
    host.updateQueue.mockRejectedValueOnce('transport failed')
    expect(await f.submit.updateQueue(item, { kind: 'remove' })).toBe(false)
    expect(await f.submit.cancel()).toBe(true)
    host.cancel.mockResolvedValueOnce(denied('nothing running'))
    expect(await f.submit.cancel()).toBe(false)
    host.cancel.mockRejectedValueOnce(new Error('cancel offline'))
    expect(await f.submit.cancel()).toBe(false)
    expect(f.notices).toContain('interrupt requested')
    expect(f.notices).toContain('queue item already claimed')
    expect(f.notices).toContain('transport failed')
    expect(f.notices).toContain('nothing running')
    expect(f.notices).toContain('cancel offline')
    f.select(undefined)
    expect(await f.submit.cancel()).toBe(false)
    expect(await f.submit.updateQueue(item, { kind: 'remove' })).toBe(false)
    expect(f.notices.at(-1)).toBe('no active session')
  })

  it('retires an observed pending echo before dispose so admitted file receipts remain consumed', async () => {
    const host = wire()
    const response = deferred<Awaited<ReturnType<typeof host.prompt>>>()
    host.prompt.mockImplementationOnce(() => response.promise)
    const f = submissionFixture(host.selected)
    const marker = f.file()
    f.enter(`admitted ${marker}`)
    host.begin[0]!.onAccept?.()
    host.begin[0]!.onRetire?.({ reason: 'observed', attachments: [] })
    f.submit.dispose()
    response.resolve(accepted)
    await flush()
    expect(f.attachments.capture(marker).content).toEqual([{ type: 'text', text: marker }])
    expect(host.prompt).toHaveBeenCalledOnce()
  })

  it.each(['other Host', 'new client', 'reconnect', 'detach'] as const)('never leaks a late cancellation notice after %s', async transition => {
    const host = wire()
    const response = deferred<Awaited<ReturnType<typeof host.cancel>>>()
    host.cancel.mockImplementationOnce(() => response.promise)
    const f = submissionFixture(host.selected)
    const cancelled = f.submit.cancel()
    f.select(transition === 'detach' ? undefined : transition === 'reconnect' ? { ...host.selected, generation: 2 } : wire(transition === 'new client' ? 'one' : 'two').selected)
    response.resolve(accepted)
    expect(await cancelled).toBe(true)
    expect(f.notices).toEqual([])
  })

  it('does not return file receipt ownership after acceptance when a pending response is disposed', async () => {
    const host = wire()
    const response = deferred<Awaited<ReturnType<typeof host.prompt>>>()
    host.prompt.mockImplementationOnce(() => response.promise)
    const f = submissionFixture(host.selected)
    const marker = f.file()
    f.enter(`admitted ${marker}`)
    host.begin[0]!.onAccept?.()
    f.submit.dispose()
    response.reject(new Error('detached'))
    await flush()
    expect(f.attachments.capture(marker).content).toEqual([{ type: 'text', text: marker }])
  })

  it('does not publish a stale queue error into a new connection generation', async () => {
    const host = wire()
    const response = deferred<Awaited<ReturnType<typeof host.updateQueue>>>()
    host.updateQueue.mockImplementationOnce(() => response.promise)
    const f = submissionFixture(host.selected)
    const changed = f.submit.updateQueue('message-1' as MessageId, { kind: 'remove' })
    f.select({ ...host.selected, generation: 2 })
    response.resolve(denied('old connection failed'))
    expect(await changed).toBe(false)
    expect(f.notices).toEqual([])
  })

  it('returns no restoration permission for a queue mutation completed after its Client was replaced', async () => {
    const host = wire()
    const response = deferred<Awaited<ReturnType<typeof host.updateQueue>>>()
    host.updateQueue.mockImplementationOnce(() => response.promise)
    const f = submissionFixture(host.selected)
    const changed = f.submit.updateQueue('message-1' as MessageId, { kind: 'remove' })
    f.select(wire('one').selected)
    response.resolve(accepted)
    expect(await changed).toBe(false)
    expect(host.updateQueue).toHaveBeenCalledOnce()
    expect(f.notices).toEqual([])
  })
})
