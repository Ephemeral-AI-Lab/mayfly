import { afterEach, describe, expect, it, vi } from 'vitest'
import type { RemoteSettingsController } from '../../src/remote/features/settings.ts'
import { RemoteAgentPresetsController, remoteAgentPresetSelection } from '../../src/remote/features/presets.ts'
import { configurationFixture, deferred, namespace } from './configuration-fixture.ts'
const mocks = vi.hoisted(() => ({ open: vi.fn() }))
vi.mock('../../src/remote/panels/browser.ts', () => ({ openRemoteBrowser: mocks.open }))
const cleanups: (() => void)[] = []
afterEach(() => { for (const cleanup of cleanups.splice(0)) cleanup() })
function fixture(options: Parameters<typeof configurationFixture>[1] = {}) {
  const test = configurationFixture(mocks.open, options)
  const roster = { presets: [{ id: 'first', name: 'First', isDefault: true }, { id: 'second', description: 'Other', isDefault: false }, { id: 'broken', broken: 'cannot load', isDefault: false }] }
  test.presets.mockResolvedValue({ ok: true, value: roster })
  const select = vi.fn(async (_id: string, preset: string): Promise<unknown> => ({ ok: true, value: preset }))
  const read = vi.fn(async (): Promise<unknown> => ({ ok: true, value: { agentPreset: 'first', content: 'plugins:\n  dsh: {}' } }))
  Object.assign(test.client.remote.agentPresets, { select, read })
  const settings = { revision: vi.fn(() => ({ descriptor: 7, fields: 'fields' })), mutate: vi.fn(async () => namespace()) }
  const controller = new RemoteAgentPresetsController(test.context, settings as unknown as RemoteSettingsController)
  cleanups.push(() => { controller.dispose(); test.dispose() })
  return { ...test, roster, settings, selectPreset: select, readPreset: read, controller }
}

describe('Remote reference Agent preset surface', () => {
  it('refuses pre-cancelled opens, retires late reads and keeps a refocused picker under its original caller', async () => {
    for (const session of [true, false]) {
      const test = fixture({ session, namespaces: [namespace('agent-preset-registry')] })
      const cancelled = new AbortController(); cancelled.abort()
      await test.controller.open(cancelled.signal)
      expect(test.presets).not.toHaveBeenCalled()
      expect(test.ctx.mayflyOverlays.focus).not.toHaveBeenCalled()
      const reading = new AbortController()
      const gate = deferred<unknown>()
      test.presets.mockReturnValueOnce(gate.promise)
      const pending = test.controller.open(reading.signal)
      reading.abort(); gate.resolve({ ok: true, value: test.roster })
      await pending
      expect(test.opened).toHaveLength(0)
      const owner = new AbortController()
      await test.controller.open(owner.signal)
      test.ctx.mayflyOverlays.focus.mockReturnValueOnce(true)
      const second = new AbortController()
      await test.controller.open(second.signal)
      second.abort()
      expect(test.opened[0]!.panel.closed).toBe(false)
      owner.abort()
      expect(test.opened[0]!.panel.closed).toBe(true)
      expect(await test.act({ kind: 'selection-accept', controlId: 'presets', selectedIds: ['first'] })).toMatchObject({ kind: 'cancelled' })
      expect(test.selectPreset).not.toHaveBeenCalled()
      expect(test.settings.mutate).not.toHaveBeenCalled()
    }
  })

  it('parses only native projection values and uses the exact shared filterable roster', async () => {
    expect(remoteAgentPresetSelection(null)).toBeNull()
    expect(remoteAgentPresetSelection('first')).toBe('first')
    expect(remoteAgentPresetSelection({ id: 'first' })).toBeUndefined()
    const test = fixture()
    test.project('first')
    await test.controller.open()
    expect(test.browser().id).toBe('mayfly.presets')
    expect(test.render()).toContain('"id":"presets"')
    expect(test.render()).toContain('"filterMode":"slash"')
    expect(test.render()).toContain('"selectedIds":["first"]')
    expect(test.render()).toContain('"disabledReason":"cannot load"')
    test.project('second')
    expect(test.render()).toContain('"selectedIds":["second"]')
    expect(test.opened[0]!.refresh).toHaveBeenCalledOnce()
  })

  it('uses the exact native Session selector and acknowledges only confirmed results', async () => {
    const test = fixture()
    await test.controller.open()
    expect(await test.act({ kind: 'selection-accept', controlId: 'presets', selectedIds: ['second'] })).toMatchObject({ kind: 'accepted', source: [], dismiss: true })
    expect(test.selectPreset).toHaveBeenCalledWith(test.selection.ref.sessionId, 'second')
    expect(test.notice.set).toHaveBeenCalledWith('Preset switched to second')
    expect(await test.act({ kind: 'selection-accept', controlId: 'presets', selectedIds: ['broken'] })).toMatchObject({ kind: 'failed' })
    expect(test.selectPreset).toHaveBeenCalledOnce()
    expect(await test.controller.select(test.selection.ref, 'first')).toBe('first')
  })

  it('stores the next-Session default with native source revisions and display label', async () => {
    const test = fixture({ session: false, namespaces: [namespace('agent-preset-registry')] })
    await test.controller.open()
    expect(await test.act({ kind: 'selection-accept', controlId: 'presets', selectedIds: ['first'] })).toMatchObject({ kind: 'accepted', dismiss: true })
    expect(test.settings.mutate).toHaveBeenCalledWith(test.client, 'agent-preset-registry', [{ op: 'set', path: ['selectedDefault'], value: 'first' }], { descriptor: 7, fields: 'fields' }, expect.any(AbortSignal))
    expect(test.notice.set).toHaveBeenCalledWith('Default preset: First')
    expect(test.selectPreset).not.toHaveBeenCalled()
  })

  it('refreshes through native roster reads and drops retired late answers or actions', async () => {
    const test = fixture()
    await test.controller.open()
    test.presets.mockResolvedValueOnce({ ok: true, value: { presets: [] } })
    expect(await test.act({ kind: 'activate', actionId: 'refresh' })).toEqual({ kind: 'completed' })
    expect(test.render()).toContain('No presets composed')
    const late = deferred<unknown>()
    test.presets.mockReturnValueOnce(late.promise)
    const refreshing = test.act({ kind: 'activate', actionId: 'refresh' })
    test.reconnect()
    late.resolve({ ok: true, value: test.roster })
    expect(await refreshing).toMatchObject({ kind: 'cancelled' })
    expect(await test.act({ kind: 'selection-accept', controlId: 'presets', selectedIds: ['first'] })).toMatchObject({ kind: 'cancelled' })
    expect(test.selectPreset).not.toHaveBeenCalled()
    expect(test.projectionListeners.size).toBe(0)
  })

  it('keeps rejected native selection visible and fences late commits after binding replacement', async () => {
    const test = fixture()
    await test.controller.open()
    test.selectPreset.mockResolvedValueOnce({ ok: false, error: { code: 'agent-preset/locked', message: 'session has started' } })
    expect(await test.act({ kind: 'selection-accept', controlId: 'presets', selectedIds: ['first'] })).toEqual({ kind: 'failed', message: 'session has started' })
    const late = deferred<unknown>()
    test.selectPreset.mockReturnValueOnce(late.promise)
    const selecting = test.act({ kind: 'selection-accept', controlId: 'presets', selectedIds: ['first'] })
    test.select({ ...test.selection, binding: {} } as typeof test.selection)
    late.resolve({ ok: true, value: 'first' })
    expect(await selecting).toMatchObject({ kind: 'cancelled' })
    expect(test.notice.set).not.toHaveBeenCalled()
  })

  it('reads complete composition documents without creating an Agent and closes them on detach', async () => {
    const test = fixture()
    await expect(test.controller.list(test.client)).resolves.toEqual(test.roster)
    await expect(test.controller.read(test.client, 'first')).resolves.toMatchObject({ content: 'plugins:\n  dsh: {}' })
    await test.controller.openDocument(test.client, 'first')
    expect(test.render()).toContain('"kind":"code"')
    expect(test.render()).toContain('plugins:')
    test.detach()
    expect(test.opened[0]!.panel.closed).toBe(true)
    await expect(test.controller.list(test.client)).resolves.toBeUndefined()
    await expect(test.controller.read(test.client, 'first')).resolves.toBeUndefined()
  })

  it('rejects catalog and document results after their Host generation retires', async () => {
    const test = fixture()
    const list = deferred<unknown>()
    const read = deferred<unknown>()
    test.presets.mockReturnValueOnce(list.promise)
    test.readPreset.mockReturnValueOnce(read.promise)
    const listing = test.controller.list(test.client)
    const reading = test.controller.read(test.client, 'first')
    test.reconnect()
    list.resolve({ ok: true, value: test.roster })
    read.resolve({ ok: true, value: { agentPreset: 'first', content: 'old' } })
    expect(await listing).toBeUndefined()
    expect(await reading).toBeUndefined()
  })

  it('opens no default roster without its namespace and acquires nothing after detach or unload', async () => {
    const test = fixture({ session: false })
    await test.controller.open()
    expect(test.opened).toEqual([])
    test.detach()
    await test.controller.open()
    await test.controller.openDocument(test.client, 'first')
    expect(test.readPreset).not.toHaveBeenCalled()
    const disposed = fixture()
    disposed.controller.dispose()
    await disposed.controller.open()
    expect(disposed.presets).not.toHaveBeenCalled()
  })

  it.each([false, true])('discards initial roster reads after exact owner retirement (reject=%s)', async rejected => {
    const test = fixture()
    const pending = Promise.withResolvers<unknown>()
    test.presets.mockReturnValueOnce(pending.promise)
    const opening = test.controller.open()
    test.reconnect()
    if (rejected) pending.reject(new Error('obsolete roster error'))
    else pending.resolve({ ok: true, value: test.roster })
    await opening
    expect(test.opened).toEqual([])
    expect(test.notice.set).not.toHaveBeenCalled()
  })

  it('reports initial roster errors and handles only admitted preset selections', async () => {
    const test = fixture()
    test.presets.mockRejectedValueOnce(new Error('roster unavailable'))
    await test.controller.open()
    expect(test.notice.set).toHaveBeenCalledExactlyOnceWith('roster unavailable')
    await test.controller.open()
    expect(await test.act({ kind: 'activate', actionId: 'other' })).toEqual({ kind: 'completed' })
    expect(await test.act({ kind: 'selection-accept', controlId: 'other', selectedIds: ['first'] })).toEqual({ kind: 'completed' })
    expect(await test.act({ kind: 'selection-accept', controlId: 'presets', selectedIds: [] })).toMatchObject({ kind: 'failed' })
    const cancelled = new AbortController(); cancelled.abort()
    expect(await test.act({ kind: 'activate', actionId: 'refresh' }, cancelled.signal)).toEqual({ kind: 'cancelled' })
    expect(test.selectPreset).not.toHaveBeenCalled()
  })

  it('uses only the newest refresh success or failure and retires cancelled native catalog reads', async () => {
    const test = fixture()
    await test.controller.open()
    const first = Promise.withResolvers<unknown>()
    test.presets.mockReturnValueOnce(first.promise)
    const stale = test.act({ kind: 'activate', actionId: 'refresh' })
    await test.act({ kind: 'activate', actionId: 'refresh' })
    first.reject(new Error('obsolete refresh failed'))
    expect(await stale).toEqual({ kind: 'cancelled' })
    test.presets.mockRejectedValueOnce(new Error('current refresh failed'))
    expect(await test.act({ kind: 'activate', actionId: 'refresh' })).toEqual({ kind: 'failed', message: 'current refresh failed' })
    const pending = Promise.withResolvers<unknown>()
    test.presets.mockReturnValueOnce(pending.promise)
    const cancelled = new AbortController()
    const reading = test.act({ kind: 'activate', actionId: 'refresh' }, cancelled.signal)
    cancelled.abort(); pending.reject(new Error('aborted refresh failed'))
    expect(await reading).toEqual({ kind: 'cancelled' })
  })

  it('keeps unnamed Session-independent defaults and failed native settings writes exact', async () => {
    const test = fixture({ session: false, namespaces: [namespace('agent-preset-registry')] })
    await test.controller.open()
    expect(test.render()).toContain('"selectedIds":["first"]')
    expect(await test.act({ kind: 'selection-accept', controlId: 'presets', selectedIds: ['second'] })).toMatchObject({ kind: 'accepted' })
    expect(test.notice.set).toHaveBeenCalledWith('Default preset: second')
    test.settings.mutate.mockRejectedValueOnce(new Error('default revision conflict'))
    expect(await test.act({ kind: 'selection-accept', controlId: 'presets', selectedIds: ['first'] })).toEqual({ kind: 'failed', message: 'default revision conflict' })
    const pending = Promise.withResolvers<ReturnType<typeof namespace>>()
    test.settings.mutate.mockReturnValueOnce(pending.promise)
    const selecting = test.act({ kind: 'selection-accept', controlId: 'presets', selectedIds: ['first'] })
    test.reconnect(); pending.reject(new Error('retired default write'))
    expect(await selecting).toEqual({ kind: 'cancelled' })
  })

  it('fences native selected events and queued projection callbacks by exact Session and owner', async () => {
    const test = fixture()
    await test.controller.open()
    expect(test.browser().isCurrent!()).toBe(true)
    test.emit('agent-preset/selected', 'foreign')
    expect(test.opened[0]!.refresh).not.toHaveBeenCalled()
    test.emit('agent-preset/selected', test.selection.ref.sessionId)
    expect(test.opened[0]!.refresh).toHaveBeenCalledOnce()
    const project = [...test.projectionListeners][0]!
    const selected = [...test.events.get('agent-preset/selected')!][0]!
    test.opened[0]!.close()
    project(); selected(test.selection.ref.sessionId)
    expect(test.opened[0]!.refresh).toHaveBeenCalledOnce()
    expect(test.browser().isCurrent!()).toBe(false)
  })

  it('refuses foreign direct selections and never presents a late native selection', async () => {
    const test = fixture()
    await test.controller.select({ ...test.selection.ref, host: 'foreign' as typeof test.selection.ref.host }, 'first')
    await test.controller.select({ ...test.selection.ref, sessionId: 'foreign' as typeof test.selection.ref.sessionId }, 'first')
    const pending = deferred<unknown>()
    test.selectPreset.mockReturnValueOnce(pending.promise)
    const selecting = test.controller.select(test.selection.ref, 'first')
    test.reconnect(); pending.resolve({ ok: true, value: 'first' })
    expect(await selecting).toBeUndefined()
    test.controller.dispose()
    expect(await test.controller.select(test.selection.ref, 'first')).toBeUndefined()
    test.select(undefined)
    expect(await test.controller.select(test.selection.ref, 'first')).toBeUndefined()
  })

  it('renders named full composition documents and fences late reads and errors after close', async () => {
    const test = fixture()
    test.readPreset.mockResolvedValueOnce({ ok: true, value: { agentPreset: 'first', name: 'Named composition', content: 'plugins: {}' } })
    await test.controller.openDocument(test.client, 'first')
    expect(test.render()).toContain('Named composition')
    expect(test.browser().isCurrent!()).toBe(true)
    test.opened[0]!.close()
    expect(test.browser().isCurrent!()).toBe(false)
    test.readPreset.mockRejectedValueOnce(new Error('document unavailable'))
    await test.controller.openDocument(test.client, 'missing')
    expect(test.notice.set).toHaveBeenCalledExactlyOnceWith('document unavailable')
    for (const rejected of [false, true]) {
      const pending = Promise.withResolvers<unknown>()
      test.readPreset.mockReturnValueOnce(pending.promise)
      const opening = test.controller.openDocument(test.client, 'first')
      test.reconnect()
      if (rejected) pending.reject(new Error('obsolete document'))
      else pending.resolve({ ok: true, value: { agentPreset: 'first', content: 'obsolete' } })
      await opening
    }
    expect(test.notice.set).toHaveBeenCalledOnce()
    expect(test.opened).toHaveLength(1)
  })
})
