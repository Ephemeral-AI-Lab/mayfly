/**
 * The built-in palettes, by key, in picker order: those for dark terminals, then those for light ones. Mayfly's own ten
 * (Mayfly Dark, the default, and Mayfly Light, Tide, Dusk, Graphite, Linen, Mist, Heather, and the high-contrast
 * Obsidian and Porcelain) follow one recipe: four neutral inks of one quiet hue, one brand hue for `primary` and the
 * tokens around it, the status hues fixed and 45° or more from `primary`. The 22 ports of ready-made palettes
 * (Catppuccin, Rosé Pine, Dracula, Nord, Tokyo Night, Solarized, Gruvbox, One, Kanagawa, Everforest) take only their
 * scheme's own colors, a tone nudged in lightness only where it would read under 4.5:1; `THIRD-PARTY-NOTICES.md` names
 * their sources and licenses. Each palette has a name and a one-line idea for the `/theme` picker, the canvas it is
 * designed and checked on, and its token tables, all generated by `docs/design/prototypes/theme-palettes.mjs` (and
 * `theme-ports.mjs`), whose `--check` holds them to their rules. Data only; `theme-dark.ts` and `theme-builtin.ts`
 * provide them as `mayflyTheme`.
 *
 * @module @ephemeral-ai/mayfly/core/palettes
 */

import { colorsFromForegrounds, themeModel, type MayflyBackgroundHexes, type MayflyForegroundHexes } from './theme-palette.ts'
import type { MayflySemanticColors } from './types.ts'

/** One built-in palette. */
export interface MayflyPalette {
  /** The `/theme` key and the `mayfly.theme` setting value. */
  readonly key: string
  /** The display name. A proper noun, never translated. */
  readonly name: string
  /** The picker's one-line description, in English (the interaction locale translates it). */
  readonly idea: string
  /** Whether the palette is drawn for a dark terminal background. */
  readonly dark: boolean
  /** `high` for the palettes whose tones reach 7:1. */
  readonly contrast?: 'high'
  /** The ready-made family a port comes from (`THIRD-PARTY-NOTICES.md`); absent on Mayfly's own palettes. */
  readonly family?: string
  /** The terminal background the palette is designed and checked on. Themes paint no background. */
  readonly canvas: string
  readonly foregrounds: MayflyForegroundHexes
  readonly backgrounds: MayflyBackgroundHexes
  /** The banner mark's inks: body, wings, and the trail from nearest to farthest. */
  readonly logoInks: readonly string[]
}

type OwnHexes = Pick<MayflyForegroundHexes, 'text' | 'textStrong' | 'muted' | 'textMuted' | 'accent' | 'primary' | 'border' | 'success' | 'error' | 'warning' | 'mdLink' | 'modelHighlight'>

/** The tokens every palette but the default repeats from its own: the aliases of the recipe, which the ports share. */
function aliased(own: OwnHexes): MayflyForegroundHexes {
  return {
    ...own,
    roleUser: own.primary,
    shellMode: own.accent,
    mdHeading: own.textStrong,
    mdLinkUrl: own.textMuted,
    mdCode: own.accent,
    mdCodeBlock: own.text,
    mdCodeBlockBorder: own.border,
    mdQuote: own.muted,
    mdQuoteBorder: own.textMuted,
    mdHr: own.border,
    mdListBullet: own.accent,
    diffAdded: own.success,
    diffRemoved: own.error,
    diffMeta: own.muted,
  }
}

