const en = Object.freeze(Object.fromEntries(Object.keys(zh).map(key => [key, key])))

/** Interaction package locale catalog. */
export const INTERACTION_LOCALE: MayflyLocaleCatalog = Object.freeze({ en, zh: Object.freeze(zh) })

/**
 * Register the package catalog whenever a locale provider is active.
 * @param ctx - interaction root context.
 */
export function mountInteractionLocale(ctx: Context): void {
  mountCommonLocale(ctx)
  ctx.inject(['mayflyLocale'], (localeCtx) => {
    localeCtx.effect(() => localeCtx.mayflyLocale.register('interaction', INTERACTION_LOCALE))
  })
}

/**
 * Return a translator that resolves the current service for every call.
 * @param ctx - frontend-tree context.
 * @returns dynamic interaction translator.
 */
export function interactionTranslator(ctx: Context): MayflyTranslate {
  return (key, values) => ctx.get('mayflyLocale')?.translate('interaction', key, values)
    ?? interpolateLocaleMessage(key, values)
}

/**
 * Observe locale/catalog revisions across provider unload and reload.
 * @param ctx - owner context.
 * @param listener - callback receiving each active provider snapshot.
 * @returns disposer for the injected observer Fiber.
 */
export function observeInteractionLocale(
  ctx: Context,
  listener: (snapshot: MayflyLocaleSnapshot | undefined) => void,
): () => void {
  let disposed = false
  let offCurrent: () => void = () => {}
  const current = ctx.get('mayflyLocale')
  if (current !== undefined) offCurrent = current.subscribe(listener)
  const fiber = ctx.inject(['mayflyLocale'], (localeCtx) => {
    /* disposing the injected Fiber prevents late activation; this is a defensive fence. */
    if (disposed) return
    offCurrent()
    const off = localeCtx.mayflyLocale.subscribe(listener)
    offCurrent = off
    localeCtx.effect(() => () => {
      off()
      /* Cordis forbids overlapping providers and serializes unload before replacement activation. */
      if (offCurrent !== off) return
      offCurrent = () => {}
      if (!disposed) listener(undefined)
    })
  })
  return () => {
    if (disposed) return
    disposed = true
    offCurrent()
    void fiber.dispose()
  }
}
